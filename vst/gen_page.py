#!/usr/bin/env python3
"""Embeds the phone pages into C++ headers as raw strings. Run by build.sh; the generated headers are
committed too, so a plain compile works without it.
  page/index.html -> ccmap_page.h      (CCMAP_PAGE, CC Map's own view)
  page/kit.html   -> ccmap_kit_page.h  (CCMAP_KIT_PAGE, the BAUKASTEN)"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
for src, hdr, var in (("index.html", "ccmap_page.h", "CCMAP_PAGE"), ("kit.html", "ccmap_kit_page.h", "CCMAP_KIT_PAGE")):
    html = open(os.path.join(here, "page", src), encoding="utf-8").read()
    if ")CCMAPPAGE\"" in html:
        sys.exit("%s contains the raw-string delimiter" % src)
    out = ("/* generated by gen_page.py from page/%s: do not edit */\n#pragma once\n" % src +
           "static const char %s[] = R\"CCMAPPAGE(" % var + html + ")CCMAPPAGE\";\n")
    open(os.path.join(here, hdr), "w", encoding="utf-8").write(out)
    print("%s: %d bytes of page" % (hdr, len(html.encode("utf-8"))))
