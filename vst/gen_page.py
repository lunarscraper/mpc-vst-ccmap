#!/usr/bin/env python3
"""Embeds page/index.html (the phone view) into ccmap_page.h as a C++ raw string. Run by build.sh;
the generated header is committed too, so a plain compile works without it."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, "page", "index.html"), encoding="utf-8").read()
if ")CCMAPPAGE\"" in html:
    sys.exit("page contains the raw-string delimiter")
out = ("/* generated by gen_page.py from page/index.html: do not edit */\n#pragma once\n"
       "static const char CCMAP_PAGE[] = R\"CCMAPPAGE(" + html + ")CCMAPPAGE\";\n")
open(os.path.join(here, "ccmap_page.h"), "w", encoding="utf-8").write(out)
print("ccmap_page.h: %d bytes of page" % len(html.encode("utf-8")))
